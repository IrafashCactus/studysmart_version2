export function useI18n() {
  const currentLang = localStorage.getItem('studySmartLang') || 'en'
  return {
    t: (key) => {
      const dict = translations[currentLang] || translations.en
      return dict[key] || translations.en[key] || key
    },
    lang: currentLang,
  }
}

export default translations

